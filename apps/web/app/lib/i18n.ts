'use client';

import { useState, useEffect } from 'react';

export type AppLocale = 'en' | 'id' | 'zh';

export const DEFAULT_LOCALE: AppLocale = 'en';

export const LOCALE_EVENT = 'mma-locale-change';

export type LanguageOption = {
  code: AppLocale;
  shortCode: string;
  name: string;
  nativeName: string;
  disabled?: boolean;
};

export const LANGUAGE_OPTIONS: LanguageOption[] = [
  { code: 'en', shortCode: 'EN', name: 'English', nativeName: 'English' },
  { code: 'id', shortCode: 'ID', name: 'Indonesian', nativeName: 'Bahasa Indonesia' },
  { code: 'zh', shortCode: 'ZH', name: 'Chinese', nativeName: '中文 (Coming Soon)', disabled: true },
];

export function getStoredLocale(): AppLocale {
  if (typeof window === 'undefined') return DEFAULT_LOCALE;
  const saved = window.localStorage.getItem('appLanguage');
  if (saved === 'id' || saved === 'zh' || saved === 'en') return saved;
  return DEFAULT_LOCALE;
}

export function setStoredLocale(locale: AppLocale) {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem('appLanguage', locale);
  window.dispatchEvent(new CustomEvent<AppLocale>(LOCALE_EVENT, { detail: locale }));
}

export function useAppLocale(): [AppLocale, (next: AppLocale) => void] {
  const [locale, setLocaleState] = useState<AppLocale>(() => getStoredLocale());

  useEffect(() => {
    const handleLocaleChange = () => {
      setLocaleState(getStoredLocale());
    };
    window.addEventListener(LOCALE_EVENT, handleLocaleChange);
    window.addEventListener('storage', handleLocaleChange);
    return () => {
      window.removeEventListener(LOCALE_EVENT, handleLocaleChange);
      window.removeEventListener('storage', handleLocaleChange);
    };
  }, []);

  const updateLocale = (next: AppLocale) => {
    setLocaleState(next);
    setStoredLocale(next);
  };

  return [locale, updateLocale];
}

